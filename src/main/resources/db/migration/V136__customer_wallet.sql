-- =============================================================================
-- V136 — Customer wallets, part 1: ownership
--
-- A wallet belonged to exactly one branch. It may now belong to exactly one customer
-- instead (a business customer of the courier company, i.e. an e-commerce portal client),
-- with the same balance, hold and ledger rules. Everything that moves money is unchanged.
--
-- owner_type says which. The CHECK makes the two shapes the only ones the table can hold:
--   BRANCH   -> branch_id set,   customer_id NULL   (every existing row)
--   CUSTOMER -> customer_id set, branch_id NULL
--
-- One wallet per customer, enforced by the database and not only by the service
-- (uk_wallets_company_customer). Several NULL customer_id values are allowed by the unique
-- key, which is what lets every branch wallet keep its NULL.
--
-- No backfill: wallet numbers are random and generated by the application, like branch
-- wallets before them. A customer without a wallet gets one on first access
-- (CustomerWalletService.getOrCreateForCustomer), and new business customers get theirs
-- when they are created.
-- =============================================================================

ALTER TABLE wallets
    MODIFY COLUMN branch_id BINARY(16) NULL,
    ADD COLUMN owner_type VARCHAR(10) NOT NULL DEFAULT 'BRANCH' AFTER wallet_number,
    ADD COLUMN customer_id BINARY(16) NULL AFTER branch_id,
    ADD UNIQUE KEY uk_wallets_company_customer (company_id, customer_id),
    ADD KEY idx_wallets_customer (customer_id),
    ADD CONSTRAINT fk_wallets_customer FOREIGN KEY (customer_id)
        REFERENCES customers (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    ADD CONSTRAINT chk_wallets_owner CHECK (
        (owner_type = 'BRANCH'   AND branch_id   IS NOT NULL AND customer_id IS NULL)
     OR (owner_type = 'CUSTOMER' AND customer_id IS NOT NULL AND branch_id   IS NULL));
